export const mandiService = {
  getMandiData: (cropId: string = 'soybean'): MandiDataPayload => {
    switch (cropId) {
      case 'cotton':
        return COTTON_HINGANGHAT_DATA;
      case 'cotton_long':
        return COTTON_LONG_HINGANGHAT_DATA;
      case 'tur':
        return TUR_HINGANGHAT_DATA;
      case 'gram':
        return GRAM_HINGANGHAT_DATA;
      case 'wheat':
        return WHEAT_HINGANGHAT_DATA;
      case 'soybean':
      default:
        return HINGANGHAT_APMC_DATA;
    }
  },

  compareWithMsp: (cropId: string = 'soybean') => {
    const data = mandiService.getMandiData(cropId);
    const diff = data.currentRate - data.mspRate;
    const isAboveMsp = diff >= 0;
    return {
      commodity: data.commodity,
      currentRate: data.currentRate,
      mspRate: data.mspRate,
      diff: Math.abs(diff),
      isAboveMsp,
      marketingSeason: data.marketingSeason,
      officialSource: data.officialSource,
      adviceHi: isAboveMsp
        ? `बाजार भाव (${data.commodity}) MSP से ₹${Math.abs(diff)} अधिक है। खुले बाजार या सीधे खरीदार को बेचना लाभदायक है।`
        : `बाजार भाव (${data.commodity}) MSP से ₹${Math.abs(diff)} कम है। शासकीय खरीद केंद्र (MSP ₹${data.mspRate}) पर पंजीकरण कराकर बेचें।`,
      adviceEn: isAboveMsp
        ? `Market rate for ${data.commodity} is ₹${Math.abs(diff)} above MSP. Profitable to sell directly in open market.`
        : `Market rate for ${data.commodity} is ₹${Math.abs(diff)} below MSP. Recommended to register and sell at Govt MSP Center.`
    };
  }
};
